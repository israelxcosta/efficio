import { useEffect, useId, useMemo, useState } from 'react';
import { Copy, MessageCircle, RotateCcw } from 'lucide-react';
import { toast } from 'sonner';
import { formatBRL, formatPhone, type DelinquencyClient } from '@effinance/shared';
import { Button } from '@/components/ui/button';
import { Modal } from '@/components/ui/dialog';
import { Label, Textarea } from '@/components/ui/input';
import { SegmentedControl } from '@/components/ui/segmented-control';
import { useAuth } from '@/features/auth/auth-context';
import { copyText } from '@/lib/clipboard';
import { pluralize } from '@/lib/utils';
import {
  buildCollectionMessage,
  collectionName,
  COMPETENCE_MODE_LABELS,
  hasOwnCompetence,
  whatsappHref,
  whatsappNumber,
  type CompetenceMode,
} from '../delinquency-message';

const COMPETENCE_KEY = 'effinance.collectionMessage.competence';

function readCompetence(): CompetenceMode {
  try {
    return localStorage.getItem(COMPETENCE_KEY) === 'due' ? 'due' : 'previous';
  } catch {
    return 'previous';
  }
}

function saveCompetence(mode: CompetenceMode): void {
  try {
    localStorage.setItem(COMPETENCE_KEY, mode);
  } catch {
    /* storage unavailable: the choice lasts while the page is open */
  }
}

/**
 * Standard collection message for a client's overdue fees, editable before copying or opening
 * WhatsApp (wa.me link) — a stopgap until a WhatsApp API is integrated.
 */
export function CollectionMessageDialog({ client, onClose }: { client: DelinquencyClient | null; onClose: () => void }) {
  const { workspace } = useAuth();
  const textId = useId();
  const [competence, setCompetence] = useState<CompetenceMode>(readCompetence);
  const [text, setText] = useState('');
  // Each opening starts a fresh text (and greeting time); the last client stays while the dialog
  // closes, so the content does not vanish mid-animation.
  const [session, setSession] = useState<{ client: DelinquencyClient; now: Date } | null>(() => (client ? { client, now: new Date() } : null));
  const [previous, setPrevious] = useState(client);
  if (client !== previous) {
    setPrevious(client);
    if (client) setSession({ client, now: new Date() });
  }
  const shown = session?.client ?? null;

  const generated = useMemo(
    () =>
      session
        ? buildCollectionMessage({
            clientName: collectionName(session.client),
            items: session.client.overdue,
            signature: workspace?.name ?? '',
            now: session.now,
            competence,
          })
        : '',
    [session, competence, workspace?.name],
  );
  useEffect(() => setText(generated), [generated]);

  const total = shown?.overdue.length ?? 0;
  // Items without their own competence (not generated by "Gerar honorários") follow the toggle.
  const derived = shown?.overdue.filter((item) => !hasOwnCompetence(item)).length ?? 0;
  const phone = shown?.phone ?? null;
  const number = whatsappNumber(phone);
  const href = number ? whatsappHref(phone, text) : null;
  const edited = text !== generated;

  async function copy() {
    if (await copyText(text)) toast.success('Mensagem copiada');
    else toast.error('Não consegui copiar. Selecione o texto e copie manualmente.');
  }

  return (
    <Modal
      open={Boolean(client)}
      onOpenChange={(open) => !open && onClose()}
      title="Mensagem de cobrança"
      description={
        shown ? (
          <>
            <span className="font-semibold text-fg">{collectionName(shown)}</span> · {pluralize(shown.overdue.length, 'mensalidade vencida', 'mensalidades vencidas')} ·{' '}
            <span className="tabular whitespace-nowrap">{formatBRL(shown.openAmount)}</span>
          </>
        ) : null
      }
      className="max-h-[calc(100dvh-2rem)] max-w-xl overflow-y-auto p-5 sm:p-6"
      footer={
        <div className="flex w-full flex-wrap items-center justify-end gap-2">
          {href ? (
            <Button asChild variant="outline" className="flex-1 sm:flex-none">
              <a href={href} target="_blank" rel="noopener noreferrer">
                <MessageCircle /> Abrir no WhatsApp
              </a>
            </Button>
          ) : null}
          <Button onClick={copy} className="flex-1 sm:flex-none">
            <Copy /> Copiar mensagem
          </Button>
        </div>
      }
    >
      <div className="flex flex-col gap-3">
        {derived > 0 ? (
          <div className="flex flex-col gap-1">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <span className="text-caption font-medium text-muted">Competência</span>
              <SegmentedControl<CompetenceMode>
                size="sm"
                ariaLabel="Competência"
                value={competence}
                onChange={(mode) => {
                  setCompetence(mode);
                  saveCompetence(mode);
                }}
                options={[
                  { value: 'previous', label: COMPETENCE_MODE_LABELS.previous },
                  { value: 'due', label: COMPETENCE_MODE_LABELS.due },
                ]}
              />
            </div>
            {derived < total ? (
              <p className="text-micro text-subtle">Honorários gerados pelo sistema já trazem a competência; a escolha vale só para os demais.</p>
            ) : null}
          </div>
        ) : (
          <p className="text-caption text-muted">Competência de cada mês conforme os honorários gerados.</p>
        )}
        <div className="flex flex-col gap-1.5">
          <div className="flex items-center justify-between gap-2">
            <Label htmlFor={textId}>Mensagem</Label>
            {edited ? (
              <Button variant="ghost" size="xs" onClick={() => setText(generated)}>
                <RotateCcw /> Restaurar texto padrão
              </Button>
            ) : null}
          </div>
          <Textarea id={textId} value={text} onChange={(e) => setText(e.target.value)} rows={13} className="text-body-sm leading-relaxed" spellCheck />
        </div>
        <p className="text-caption text-muted">
          {number ? (
            <>
              WhatsApp: <span className="tabular font-semibold text-fg">{formatPhone(number.slice(2))}</span>
              {shown?.responsibleName ? ` · ${shown.responsibleName}` : ''}
            </>
          ) : phone ? (
            'O telefone cadastrado não parece um celular ou fixo com DDD. Copie a mensagem e envie pelo WhatsApp.'
          ) : (
            'Cliente sem telefone cadastrado. Copie a mensagem e envie pelo WhatsApp.'
          )}
        </p>
      </div>
    </Modal>
  );
}
